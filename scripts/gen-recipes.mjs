function r(id, nom, emoji, tempsMin, tags, regimes, equipement, allergenes, kcal, macros, ings, etapes) {
  const ingredients = ings.map(([nom, qteParPersonne, unite, rayon, prix]) => ({
    nom,
    qteParPersonne,
    unite,
    rayon,
    prixParPersonne: Math.round(prix * 100) / 100,
  }));
  const prixParPersonne =
    Math.round(ingredients.reduce((s, i) => s + i.prixParPersonne, 0) * 100) / 100;
  return {
    id,
    nom,
    tempsMin,
    tags,
    regimes,
    allergenes,
    equipement,
    prixParPersonne,
    kcal,
    macros,
    emoji,
    ingredients,
    etapes,
  };
}

